# ui.sh — общение с пользователем: подсказки, вопросы, подтверждения.

usage() {
  cat <<USAGE
$PROG $VERSION — синхронизация активности приватных репозиториев в GitHub

Команды:
  setup            интерактивная настройка с нуля: зеркало, источники, remote
  init [каталог]   создать зеркало (спросит имя и почты, если не переданы)
  add [путь]       добавить источник (спросит путь, если не передан)
  sync             добавить пустые коммиты для новых исходных коммитов и запушить
  status           статистика зеркала
  sources          список источников

Флаги sync:  --dry-run  --no-push  --no-fetch  --since ГГГГ-ММ-ДД
Флаги init:  --name <имя>  --email <почта>[,<почта>...]
Общий флаг:  --mirror <каталог>

Каталог зеркала ищется так: --mirror, затем \$GITMIRROR_DIR, затем текущий
каталог, если в нём лежит $CONFIG_NAME.

Быстрый старт:
  $PROG setup
USAGE
}

# ask <переменная> <вопрос> [дефолт] — читает с терминала, не из пайпа
ask() {
  local __var="$1" __q="$2" __def="${3:-}" __ans="" __prompt
  [ -t 0 ] || die "нужен интерактивный терминал (или передай значение флагом)"
  if [ -n "$__def" ]; then __prompt="$__q [$__def]: "; else __prompt="$__q: "; fi
  read -r -e -p "$__prompt" __ans </dev/tty || true
  [ -z "$__ans" ] && __ans="$__def"
  eval "$__var=\$__ans"
}

confirm() {
  local __ans=""
  [ -t 0 ] || return 0
  read -r -p "$1 [Y/n]: " __ans </dev/tty || true
  case "$__ans" in [nN]*) return 1 ;; *) return 0 ;; esac
}
